export function isNotFranchise(name = '') {
  const normalized = (name ?? '').toLowerCase();
  return !franchiseKeywords.some((keyword) => normalized.includes(keyword.toLowerCase()));
}

export function filterFranchise(restaurants = []) {
  return restaurants.filter((restaurant) => isNotFranchise(restaurant.name));
}
